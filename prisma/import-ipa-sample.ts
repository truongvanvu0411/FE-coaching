async function main() {
  console.log(`Importing ${QUESTIONS.length} IPA public sample questions...`);
  const topics = await prisma.topic.findMany({ where: { section: "A" } });
  const topicIdByName = new Map(topics.map((t) => [t.nameJa, t.id]));

  for (const q of QUESTIONS) {
    const topicId = topicIdByName.get(q.topic);
    if (!topicId) throw new Error(`Unknown topic: ${q.topic}`);

    const id = `FE-A-IPA-SAMPLE-Q${String(q.n).padStart(2, "0")}`;
    await prisma.question.upsert({
      where: { id },
      update: {},
      create: {
        id,
        section: "A",
        year: YEAR,
        sourceType: "IPA_PUBLIC",
        sourceUrl: SOURCE_URL,
        sourcePage: String(q.page),
        questionNumber: `問${q.n}`,
        topicId,
        difficulty: q.difficulty,
        bodyJa: q.body,
        correctAnswer: q.correct,
        verified: true,
        reviewStatus: "VERIFIED",
        choices: {
          create: (["A", "B", "C", "D"] as const).map((key, i) => ({
            key,
            textJa: q.choices[i],
            order: i,
          })),
        },
      },
    });
  }

  console.log("Done.");
}

main()
  .catch((err) => {
    console.error(err);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
